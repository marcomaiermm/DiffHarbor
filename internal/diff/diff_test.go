func TestDiff(t *testing.T) {
	file := func(p, hunk string) string {
		return "diff --git a/" + p + " b/" + p + "\nindex 1..2 100644\n--- a/" + p + "\n+++ b/" + p + "\n" + hunk
	}
	src := file("src/a.ts", "@@ -1,3 +10,4 @@ fn\n ctx\n-old\n+new\n+new2\n ctx2\n")
	diff := src + file("pnpm-lock.yaml", "@@ -1 +1 @@\n-a\n+b\n") +
		"diff --git a/gone.ts b/gone.ts\ndeleted file mode 100644\n--- a/gone.ts\n+++ /dev/null\n@@ -1 +0,0 @@\n-x\n"
	if got, _ := Filter(diff, "", nil, nil, 1); len(got) != 1 || got[0] != src+"\n# 1 file(s) deleted: gone.ts. Check that nothing still uses them.\n" {
		t.Fatalf("filterDiff: %q", got)
	}
	if got, _ := Filter(diff, "", map[string]bool{"other.ts": true}, nil, 1); got != nil {
		t.Fatalf("filterDiff only: %q", got)
	}
	if got, _ := Filter(file("big.ts", strings.Repeat("+x", Max)), "", nil, nil, 4); len(got) != 1 || !strings.HasPrefix(got[0], "\n# 1 more file(s) omitted") {
		t.Fatalf("filterDiff big: %q", got)
	}
	want := map[string]bool{"src/a.ts:10": true, "src/a.ts:11": true, "src/a.ts:12": true, "src/a.ts:13": true}
	if got := RightLines(src, true); !maps.Equal(got, want) {
		t.Fatalf("rightLines: %v", got)
	}
	if got := RightLines(src, false); !maps.Equal(got, map[string]bool{"src/a.ts:11": true, "src/a.ts:12": true}) {
		t.Fatalf("rightLines added: %v", got)
	}
	want["pnpm-lock.yaml:1"] = true // and nothing for the deleted gone.ts
	if got := RightLines(diff, true); !maps.Equal(got, want) {
		t.Fatalf("rightLines deleted file: %v", got)
	}
	if got := Paths(src); len(got) != 1 || got[0] != "src/a.ts" {
		t.Fatalf("paths: %v", got)
	}
}

func TestPatchIDs(t *testing.T) {
	reviewed := "diff --git a/a.go b/a.go\nindex 1..2 100644\n--- a/a.go\n+++ b/a.go\n@@ -3,3 +3,3 @@ func f() {\n ctx\n-old\n+new\n ctx\n" +
		"diff --git a/b.go b/b.go\nindex 3..4 100644\n--- a/b.go\n+++ b/b.go\n@@ -1 +1 @@\n-x\n+y\n"
	// Rebased: main moved a.go's lines and context, b.go got a fix on top.
	rebased := "diff --git a/a.go b/a.go\nindex 7..8 100644\n--- a/a.go\n+++ b/a.go\n@@ -9,3 +9,3 @@ func g() {\n other\n-old\n+new\n other\n" +
		"diff --git a/b.go b/b.go\nindex 3..5 100644\n--- a/b.go\n+++ b/b.go\n@@ -1 +1 @@\n-x\n+z\n"
	a, b := PatchIDs(reviewed), PatchIDs(rebased)
	if len(a) != 2 || a["a.go"] != b["a.go"] || a["b.go"] == b["b.go"] {
		t.Fatalf("patchIDs: %v %v", a, b)
	}
}

func TestSkipAndOmitted(t *testing.T) {
	for _, p := range []string{"api/x.pb.go", "src/routeTree.gen.ts", "web/styles.gen.css", "web/__generated__/q.ts", ".terraform.lock.hcl", "Gemfile.lock",
		"ios/Podfile.lock", "flake.lock", "gradle.lockfile", "third_party/x/a.js", "api/zz_generated.deepcopy.go", "db/query.sql.go",
		"lib/a.g.dart", "gen/api_pb.ts"} {
		if !Skip.MatchString(p) {
			t.Errorf("not skipped: %s", p)
		}
	}
	if Skip.MatchString("src/generator.ts") || Skip.MatchString("src/lock.ts") {
		t.Error("skipped generator.ts or lock.ts")
	}
	// generated by the file's first lines, not its name
	gen := func(p, hunk string) string {
		return "diff --git a/" + p + " b/" + p + "\n--- a/" + p + "\n+++ b/" + p + "\n" + hunk
	}
	for _, c := range []struct {
		f    string
		skip bool
	}{
		{gen("db/models.go", "@@ -0,0 +1,3 @@\n+// Code generated by sqlc. DO NOT EDIT.\n+\n+package db\n"), true},
		{gen("lib/a.dart", "@@ -1,3 +1,3 @@\n // GENERATED CODE - DO NOT MODIFY BY HAND\n-a\n+b\n"), true},
		{gen("src/a.ts", "@@ -1,2 +1,2 @@\n /**\n- * @generated\n+ * @generated SignedSource\n"), true},
		{gen("src/b.ts", "@@ -40,2 +40,2 @@\n-// Code generated by hand. DO NOT EDIT.\n+x\n"), false}, // not its first lines
		{gen("src/c.ts", "@@ -1,2 +1,2 @@\n-a\n+// generated by the build: do not edit dist/ by hand\n"), true},
		{gen("src/d.ts", "@@ -1,2 +1,2 @@\n-a\n+// see the generated code\n"), false},
		{gen("gen/doc.go", "@@ -0,0 +1 @@\n+// Package gen writes files headed \"// Code generated by gen. DO NOT EDIT.\"\n"), false},
		{gen("t/skip.py", "@@ -0,0 +1 @@\n+# Checks that files marked @generated are skipped\n"), false},
		{gen("x.py", "@@ -0,0 +1 @@\n+# This file was generated by protoc. Do not edit.\n"), true},
		{gen("lic.go", "@@ -0,0 +1,12 @@\n"+strings.Repeat("+// Licensed under the Apache License.\n", 10)+"+// Code generated by x. DO NOT EDIT.\n+package a\n"), true},
	} {
		if got, _ := Filter(c.f, "", nil, nil, 1); (got == nil) != c.skip {
			t.Errorf("generated %v: %q", c.skip, c.f)
		}
	}
	// A change lower in a generated file: its header is read in the checkout.
	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, "db"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "db", "models.go"), []byte("// Code generated by sqlc. DO NOT EDIT.\n\npackage db\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	low := gen("db/models.go", "@@ -40,2 +40,3 @@\n x\n+y\n x\n")
	if got, _ := Filter(low, root, nil, nil, 1); got != nil {
		t.Errorf("generated in the checkout: %q", got)
	}
	if got, _ := Filter(low, "", nil, nil, 1); got == nil {
		t.Error("no checkout: reviewed")
	}
	file := func(p string) string {
		return "diff --git a/" + p + " b/" + p + "\n+++ b/" + p + "\n" + strings.Repeat("+x", Max/4) + "\n"
	}
	if got, n := Filter(file("a.ts")+file("b.ts")+file("c.ts"), "", nil, nil, 1); len(n) != 2 || !strings.HasSuffix(got[0], "read them in the repo: b.ts, c.ts\n") {
		t.Fatalf("omitted: %q", got[0][max(0, len(got[0])-100):])
	}
	// code fills the budget first, stylesheets with data, docs last: the input order doesn't matter
	all := file("docs/a.md") + file("web/a.css") + file("tests/c.test.ts") + file("drizzle/s.json") + file("src/b.ts")
	got, _ := Filter(all, "", nil, nil, 1)
	if !strings.HasPrefix(got[0], "diff --git a/src/b.ts") || !strings.HasSuffix(got[0], "read them in the repo: tests/c.test.ts, web/a.css, drizzle/s.json, docs/a.md\n") {
		t.Fatalf("order: %q … %q", got[0][:40], got[0][max(0, len(got[0])-100):])
	}
	// In parts nothing is left out, files of one directory share a part, each part keeps the diff's order.
	sized := func(p string, tenths int) string {
		return "diff --git a/" + p + " b/" + p + "\n+++ b/" + p + "\n" + strings.Repeat("x", Max*tenths/10-50) + "\n"
	}
	got, n := Filter(sized("a/1.ts", 4)+sized("b/1.ts", 7)+sized("b/2.ts", 2)+sized("a/2.ts", 1), "", nil, nil, 3)
	var paths []string
	for _, p := range got {
		paths = append(paths, strings.Join(Paths(p), " "))
	}
	if len(n) != 0 || strings.Join(paths, ", ") != "a/1.ts a/2.ts, b/1.ts b/2.ts" {
		t.Fatalf("parts: %v, %v omitted", paths, n)
	}
	// A file past Max in pieces, each a diff of the file: together its old and new lines, a piece left out named.
	var body strings.Builder
	for i := range 3000 {
		body.WriteString([]string{" ctx ", "-old ", "+new "}[i%3] + strings.Repeat("y", 40) + "\n")
	}
	big := "diff --git a/big.go b/big.go\n--- a/big.go\n+++ b/big.go\n@@ -1,2000 +1,2000 @@ func f\n" + body.String()
	got, n = Filter(big, "", nil, nil, 4)
	if len(got) != 3 || len(n) != 0 || !maps.Equal(NewLines(strings.Join(got, "")), NewLines(big)) ||
		!slices.Equal(Paths(strings.Join(got, "")), []string{"big.go"}) {
		t.Fatalf("pieces: %d parts, %v omitted", len(got), n)
	}
	from := 1
	for _, p := range got {
		if len(p) > Max || !strings.HasPrefix(p, "diff --git a/big.go b/big.go\n--- a/big.go\n+++ b/big.go\n@@ ") || !strings.Contains(p, " @@ func f\n") {
			t.Fatalf("piece: %d chars, %q", len(p), p[:min(len(p), 120)])
		}
		for _, r := range OldRanges(p) {
			if r[0] != from {
				t.Fatalf("old lines: %v from %d", OldRanges(p), from)
			}
			from = r[1]
		}
	}
	if from != 2001 {
		t.Fatalf("old lines end at %d", from)
	}
	if got, n = Filter(big, "", nil, nil, 2); len(got) != 2 || !slices.Equal(n, []string{"big.go"}) || !strings.HasSuffix(got[1], "read them in the repo: big.go\n") {
		t.Fatalf("a piece left out: %d parts, %v", len(got), n)
	}
	// A cut between a hunk's removed and added lines: the side with none names the line before.
	one := "diff --git a/z.go b/z.go\n--- a/z.go\n+++ b/z.go\n@@ -8571,1 +8571,1 @@\n-" + strings.Repeat("a", Max/2) + "\n+" + strings.Repeat("b", Max/2) + "\n"
	if got := split(one); len(got) != 2 || !strings.Contains(got[0], "@@ -8571,1 +8570,0 @@") || !strings.Contains(got[1], "@@ -8571,0 +8571,1 @@") {
		t.Fatalf("zero-count starts: %q", []string{got[0][:min(len(got[0]), 90)], got[len(got)-1][:min(len(got[len(got)-1]), 90)]})
	}
	// A last line near Max leaves no piece with only the header; a no-newline marker stays with its line.
	z := "diff --git a/z.go b/z.go\n--- a/z.go\n+++ b/z.go\n"
	if got := split(z + "@@ -1 +1 @@\n+" + strings.Repeat("x", Max-60) + "\n"); len(got) != 1 {
		t.Fatalf("header-only piece: %d pieces", len(got))
	}
	nl := "\\ No newline at end of file\n"
	for _, p := range split(z + "@@ -1,2 +1,2 @@\n c\n-" + strings.Repeat("a", Max-97) + "\n" + nl + "+b\n") {
		if len(p) > Max || strings.Contains(p, "@@\n"+nl) || strings.Contains(p, "aaa\n") && !strings.HasSuffix(p, "a\n"+nl) {
			t.Fatalf("no-newline marker: %d chars, %q", len(p), p[max(0, len(p)-60):])
		}
	}
	if Docs(all) != file("docs/a.md") {
		t.Fatalf("docs: %q", Docs(all))
	}
}

func TestOverlap(t *testing.T) {
	ours := OldRanges("diff --git a/x b/x\n@@ -10,7 +10,8 @@ func a\n ctx\n@@ -40 +41 @@\n-a\n+b\n")
	if want := [][2]int{{10, 17}, {40, 41}}; !slices.Equal(ours, want) {
		t.Fatalf("OldRanges = %v, want %v", ours, want)
	}
	for _, c := range []struct {
		patch string
		want  bool
	}{
		{"@@ -16,3 +16,4 @@\n", true},  // shares line 16
		{"@@ -17,3 +17,3 @@\n", false}, // starts where ours ends
		{"@@ -40,0 +41,2 @@\n", true},  // inserts at 40
		{"@@ -1,3 +1,3 @@\n", false},
	} {
		if got := Overlap(ours, OldRanges(c.patch)); got != c.want {
			t.Errorf("Overlap(%q) = %v, want %v", c.patch, got, c.want)
		}
	}
}
