func TestMapReach(t *testing.T) {
	d := Data{Diff: newFile("a/a.go", "package a\n") + newFile("b/b.go", "package b\n")}
	syms := map[string][]Symbol{}
	for i := range 32 { // past maxAffected
		s := changedSym("a/a.go", 3+i, "changed")
		s.NOutside, s.Outside = 1+i%3, []Ref{{Path: "x/x.go", Line: 1}}
		syms[fmt.Sprintf("F%02d", i)] = []Symbol{s}
	}
	// 25 places, 9 of them in tests, past the 20 kept: the split holds
	big := changedSym("b/b.go", 3, "signature")
	big.NOutside, big.NOutsideTests = 25, 9
	big.Outside = []Ref{{Path: "x/x.go", Line: 2}, {Path: "x/x_test.go", Line: 3}}
	syms["Big"] = []Symbol{big}
	only := changedSym("b/b.go", 9, "changed") // named in tests only: leaves the list
	only.NOutside, only.NOutsideTests = 2, 2
	syms["Only"] = []Symbol{only}
	d.Symbols = syms
	m := BuildMap(nil, d, nil)
	b := mapPart(m, "b")
	if b.Reach != 16 || b.Tests != 11 {
		t.Errorf("b reach %d, tests %d", b.Reach, b.Tests)
	}
	r := m.Reach
	if r.Decls != 33 || r.More != 3 || len(r.List) != maxAffected || r.Tests != 11 {
		t.Errorf("reach %d decls, %d more, %d listed, %d in tests", r.Decls, r.More, len(r.List), r.Tests)
	}
	// the cut keeps the signature change and the tests' places leave its list
	if k := slices.IndexFunc(r.List, func(x MapReachDecl) bool { return x.Name == "Big" }); k < 0 || r.List[k].N != 16 || len(r.List[k].Places) != 1 || r.List[k].Places[0].Path != "x/x.go" {
		t.Errorf("list %+v", r.List)
	}
	if slices.ContainsFunc(r.List, func(x MapReachDecl) bool { return x.Name == "Only" }) {
		t.Error("a declaration named in tests only is listed")
	}
	sum := 0
	for _, p := range m.Parts {
		sum += p.Reach
	}
	if sum != r.Places {
		t.Errorf("parts sum %d, places %d", sum, r.Places)
	}
}

