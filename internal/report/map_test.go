// newFile is the diff of a file the PR adds, every line added.
func newFile(p, body string) string {
	ls := strings.Split(strings.TrimSuffix(body, "\n"), "\n")
	return fmt.Sprintf("diff --git a/%s b/%s\nnew file mode 100644\n--- /dev/null\n+++ b/%s\n@@ -0,0 +1,%d @@\n+%s\n", p, p, p, len(ls), strings.Join(ls, "\n+"))
}

func goneFile(p string) string {
	return fmt.Sprintf("diff --git a/%s b/%s\ndeleted file mode 100644\n--- a/%s\n+++ /dev/null\n@@ -1 +0,0 @@\n-x\n", p, p, p)
}

// changedSym is a changed declaration the index resolved, its uses in the diff's files "path:line" or "path:line=kind".
func changedSym(p string, line int, state string, here ...string) Symbol {
	s := Symbol{Kind: "function", Path: p, Line: line, From: line, To: line + 2, Exact: true, State: state}
	for _, h := range here {
		at, kind, _ := strings.Cut(h, "=")
		s.Here, s.HereKind = append(s.Here, at), append(s.HereKind, kind)
	}
	return s
}

func mapLine(m *Map, from, to string) *MapLine {
	for i, l := range m.Lines {
		if l.From == from && l.To == to {
			return &m.Lines[i]
		}
	}
	return nil
}

func mapPart(m *Map, id string) MapPart {
	for _, p := range m.Parts {
		if p.ID == id {
			return p
		}
	}
	return MapPart{}
}

func TestMapParts(t *testing.T) {
	var d strings.Builder
	for i := range 20 { // one folder each: 20 parts at depth 1, past 16
		d.WriteString(newFile(fmt.Sprintf("d%02d/x.go", i), "package x\n"))
	}
	d.WriteString(newFile("d19/y.go", "package x\n")) // the biggest stay
	d.WriteString(newFile("d18/y.go", "package x\n"))
	m := BuildMap(nil, Data{Diff: d.String()}, nil)
	if len(m.Parts) != 16 {
		t.Fatalf("%d parts, want 15 and Other", len(m.Parts))
	}
	o := mapPart(m, "other")
	if o.Label != "Other · 5 folders" || len(o.Files) != 5 || m.Parts[15].ID != "other" || mapPart(m, "d19").ID == "" || mapPart(m, "d18").ID == "" {
		t.Errorf("other %+v", o)
	}

	// the deepest level, three, that gives at most 16; labels keep a parent when they start with _ or are shared
	d.Reset()
	for _, p := range []string{
		"src/routes/_protected/a.ts", "src/routes/_protected/team/b.ts", "cmd/ingest/c.go", "internal/ingest/e.go",
		"top.go", "tests/t.go", "a_test.go", "vite.config.ts", "gen/zz_gen.go", "lib/h.ts",
	} {
		d.WriteString(newFile(p, "x\n"))
	}
	d.WriteString(newFile("gen/api.go", "// Code generated by x. DO NOT EDIT.\npackage gen\n"))
	d.WriteString(goneFile("lib/old.ts") + goneFile("lib/more/old.ts") + goneFile("pkg/a/b.ts") + goneFile("pkg/a/c.ts") + goneFile("pkg/z/d.ts"))
	m = BuildMap(nil, Data{Diff: d.String()}, nil)
	var labels []string
	for _, p := range m.Parts {
		labels = append(labels, p.ID+"="+p.Label)
	}
	want := []string{".=top level", "cmd/ingest=cmd/ingest", "internal/ingest=internal/ingest", "lib=lib", "src/routes/_protected=routes/_protected"}
	if !slices.Equal(labels, want) { // depth 3 gives 5 parts, _protected keeps its parent; tests and tool config aside
		t.Errorf("parts %q", labels)
	}
	if lib := mapPart(m, "lib"); lib.Deleted != 1 || len(lib.Files) != 1 {
		t.Errorf("lib %+v", lib) // lib/old.ts is plus 1 deleted; lib/more has no kept file: Removed
	}
	if r := m.Removed; r == nil || r.N != 4 || !reflect.DeepEqual(r.Folders, []MapFolder{{"pkg/a", 2}, {"lib/more", 1}, {"pkg/z", 1}}) {
		t.Errorf("removed %+v", r)
	}
	if g := m.Generated; g == nil || !slices.Equal(g.Files, []string{"gen/api.go", "gen/zz_gen.go"}) {
		t.Errorf("generated %+v", g)
	}
}

